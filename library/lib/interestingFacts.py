from operator import itemgetter
class Priority:
    def __init__(self):
        self.data = []
        self._counter = 0

    def enqueue(self, name, info, distance):
        self._counter += 1
        fact={
            "name": name,
            "info": info,
            "distance": distance,
            "id": self._counter
        }
        self.data.append(fact)
        self.data.sort(key=itemgetter('distance', 'id'))

    def get_nearest(self):
        if len(self.data) > 0:
            return self.data[0]    
        else:                        
            return None
    
    def get_farthest(self):
        if len(self.data) > 0:
            return self.data[-1]
        else:
         return None

    def get_oldest(self):
        if len(self.data) > 0:
            result = min(self.data, key=itemgetter('id'))
            return result
        else:
            return None
    
    def display(self):
        print(f"\n--- СПИСОК ФАКТІВ (Завантажено: {len(self.data)}) ---")
        for item in self.data:
            print(f"ID:{item['id']} | {item['name']} — {item['distance']} св. р.")

